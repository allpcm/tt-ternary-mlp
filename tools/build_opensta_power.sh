#!/usr/bin/env bash
# OpenSTA + CUDD on Thor (aarch64), then annotated power.
#
# v4. What v3 got wrong: aarch64 detection was never broken - CUDD's
# configure reported aarch64-unknown-linux-gnu correctly. Refreshing
# config.guess/config.sub made them newer than aclocal.m4 and Makefile.in,
# which triggered autotools' maintainer rebuild rules, which called
# aclocal-1.14 (the version CUDD was packaged with) against a system that
# has 1.16. That is mtime skew, caused by the "fix".
#
# Correct approach: throw the tree away and regenerate the entire build
# system with the installed automake, so every generated file is consistent
# and newer than its inputs by construction.
#
#   cd ~/tt-power && bash build_power4.sh

set -uo pipefail
D="$(cd "$(dirname "$0")" && pwd)"; cd "$D"
PDK_HASH=8afc8346a57fe1ab7934ba5a6056ea8b43078e71
CUDD_PREFIX="$D/cudd-install"
say() { printf '\n=== %s ===\n' "$1"; }
die() { printf '\nSTOP: %s\n' "$1"; exit 1; }
dump() { printf '\n----- %s -----\n' "$1"; tail -"${2:-20}" "$1" 2>/dev/null || echo "(absent)"; }

say "inputs"
for f in gl/tt_um_pcm_ternary_mlp.v gl/tt_um_pcm_ternary_mlp.sdc gl/tb.real.vcd; do
  [ -f "$f" ] || die "missing $f"
  printf '  %-34s %10d bytes\n' "$f" "$(wc -c <"$f")"
done

# ------------------------------------------------------------------ CUDD --
if [ -f "$CUDD_PREFIX/lib/libcudd.a" ]; then
  say "CUDD already built, skipping"
else
  say "autotools"
  sudo apt-get install -y -qq autoconf automake libtool m4 perl || die "autotools install failed"
  automake --version | head -1 | sed 's/^/  /'

  say "fresh CUDD clone (the old tree has skewed timestamps)"
  rm -rf "$D/cudd"
  git clone --depth 1 https://github.com/The-OpenROAD-Project/cudd.git "$D/cudd" 2>&1 | tail -1 \
    || die "could not clone CUDD"

  say "regenerating the build system with the installed automake"
  # -f forces replacement of files generated by an older automake, -i installs
  # any missing aux scripts (including current config.guess/config.sub, which
  # is why v3's manual copy was never needed).
  ( cd "$D/cudd" && autoreconf -fi >autoreconf.log 2>&1 ) || {
    dump "$D/cudd/autoreconf.log" 30
    die "autoreconf failed (log above)"
  }
  echo "  autoreconf OK"

  say "configuring CUDD"
  ( cd "$D/cudd" && ./configure --prefix="$CUDD_PREFIX" --enable-obj --enable-dddmp \
      >configure.log 2>&1 ) || { dump "$D/cudd/configure.log" 30; die "configure failed"; }
  sed -n '/Configuration summary/,/^--------/p' "$D/cudd/configure.log" | sed 's/^/  /'

  say "compiling CUDD"
  ( cd "$D/cudd" && make -j"$(nproc)" >make.log 2>&1 && make install >install.log 2>&1 ) || {
    grep -inE "error|fatal|not found|No such" "$D/cudd/make.log" | head -15
    dump "$D/cudd/make.log" 20
    die "CUDD build failed (errors above)"
  }
fi
ls -1 "$CUDD_PREFIX"/lib/libcudd.* 2>/dev/null | sed 's/^/  /' || die "no libcudd in $CUDD_PREFIX/lib"
find "$CUDD_PREFIX/include" -name 'cudd.h' | sed 's/^/  /' | head -2

# --------------------------------------------------------------- OpenSTA --
if [ -x "$D/OpenSTA/build/sta" ]; then
  say "OpenSTA already built, skipping"
else
  say "OpenSTA dependencies"
  sudo apt-get install -y -qq build-essential cmake git tcl-dev swig bison flex \
      libeigen3-dev zlib1g-dev libreadline-dev || die "dependency install failed"
  [ -d "$D/OpenSTA/.git" ] || {
    rm -rf "$D/OpenSTA"
    git clone --depth 1 https://github.com/parallaxsw/OpenSTA.git "$D/OpenSTA" 2>&1 | tail -1 \
      || git clone --depth 1 https://github.com/The-OpenROAD-Project/OpenSTA.git "$D/OpenSTA" 2>&1 | tail -1 \
      || die "could not clone OpenSTA"
  }

  say "configuring OpenSTA against CUDD"
  rm -rf "$D/OpenSTA/build"
  mkdir -p "$D/OpenSTA/build"
  ( cd "$D/OpenSTA/build" && cmake .. -DCUDD_DIR="$CUDD_PREFIX" >cmake.log 2>&1 ) || {
    grep -inE "error|NOTFOUND" "$D/OpenSTA/build/cmake.log" | head -15
    dump "$D/OpenSTA/build/cmake.log" 25
    die "cmake failed (above)"
  }
  grep -i cudd "$D/OpenSTA/build/cmake.log" | head -3 | sed 's/^/  /'

  say "compiling OpenSTA (slow)"
  ( cd "$D/OpenSTA/build" && make -j"$(nproc)" >make.log 2>&1 ) || {
    grep -inE "error|fatal" "$D/OpenSTA/build/make.log" | head -20
    die "make failed (errors above; full log OpenSTA/build/make.log)"
  }
fi
STA="$D/OpenSTA/build/sta"
[ -x "$STA" ] || die "sta not found at $STA"
say "sta"; "$STA" -version 2>&1 | head -1 | sed 's/^/  /'

# ------------------------------------------------------------------- PDK --
LIB=$(find "$D/pdk" -name 'sky130_fd_sc_hd__tt_025C_1v80.lib' 2>/dev/null | head -1)
if [ -z "$LIB" ]; then
  say "fetching sky130 liberty (open_pdks $PDK_HASH)"
  sudo apt-get install -y -qq python3-venv >/dev/null 2>&1
  python3 -m venv "$D/.venv" 2>/dev/null || die "venv creation failed"
  "$D/.venv/bin/pip" install -q --upgrade pip volare || die "volare install failed"
  "$D/.venv/bin/volare" enable --pdk sky130 --pdk-root "$D/pdk" "$PDK_HASH" 2>&1 | tail -5
  LIB=$(find "$D/pdk" -name 'sky130_fd_sc_hd__tt_025C_1v80.lib' 2>/dev/null | head -1)
  [ -n "$LIB" ] || die "liberty not found under $D/pdk"
fi
say "liberty"; echo "  $LIB"

# ------------------------------------------------------------------- run --
cat > "$D/power.tcl" <<TCL
# Annotated power, tt_um_pcm_ternary_mlp. Activity from the real cocotb
# vector set, not a default switching factor - which matters because 320 of
# the 419 flip-flops are the weight register and it does not toggle during
# inference at all.
read_liberty $LIB
read_verilog $D/gl/tt_um_pcm_ternary_mlp.v
link_design tt_um_pcm_ternary_mlp
read_sdc $D/gl/tt_um_pcm_ternary_mlp.sdc
read_vcd -scope tb/user_project $D/gl/tb.real.vcd

puts "\n########## ANNOTATED POWER ##########"
report_power -digits 4

puts "\n########## TIMING SANITY ##########"
report_checks -path_delay max -digits 3
report_checks -path_delay min -digits 3
exit
TCL

say "running OpenSTA"
"$STA" -no_splash -exit "$D/power.tcl" 2>&1 | tee "$D/power_report.txt"
say "done"; echo "saved to $D/power_report.txt"
